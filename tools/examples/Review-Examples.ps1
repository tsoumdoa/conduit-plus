param(
    [string]$Output = (Join-Path $PSScriptRoot '../../artifacts/final-review')
)
$ErrorActionPreference = 'Stop'
$destination = [IO.Path]::GetFullPath($Output)
New-Item -ItemType Directory -Force $destination | Out-Null
$logs = Join-Path $destination 'logs'
New-Item -ItemType Directory -Force $logs | Out-Null
# Each wrapper call starts a fresh RhinoCore: never capture two viewport states in one host.
$shots = @('paper', 'night', 'smoke', 'blueprint', 'paper-selected', 'paper-group', 'paper-partial', 'paper-scale-half', 'paper-scale-two')
foreach ($fixture in @('Showcase', 'Hello')) {
    $fixtureShots = if ($fixture -eq 'Hello') { @('paper') } else { $shots }
    $first = $true
    foreach ($shot in $fixtureShots) {
        $arguments = @{ Example = $fixture; Shot = $shot; Safe = $true; Output = $destination; VerifyOnly = -not $first; ReviewCaptureChecks = $true }
        $arguments.PlanScale = switch ($shot) { 'paper-scale-half' { 0.5 }; 'paper-scale-two' { 2 }; default { 1 } }
        for ($attempt = 1; $attempt -le 6; $attempt++) {
            try {
                & (Join-Path $PSScriptRoot 'Build-Examples.ps1') @arguments
                break
            } catch {
                $errorLog = Get-Content (Join-Path $destination 'example-error.log') -Raw -ErrorAction SilentlyContinue
                $nativeFailure = $errorLog -match 'AccessViolation|SEHException|Fatal error|Unhandled exception.*native' -or [string]::IsNullOrWhiteSpace($errorLog)
                $incompleteCapture = $errorLog -match 'Incomplete review capture:'
                $limit = if ($incompleteCapture) { 6 } else { 2 }
                if ($attempt -ge $limit -or (-not $nativeFailure -and -not $incompleteCapture)) { throw }
                Write-Output "Retrying $fixture/$shot in a fresh host after native failure or incomplete scene capture (attempt $attempt of $limit)."
            } finally {
                foreach ($suffix in @('', '-error')) {
                    $source = Join-Path $destination "example$suffix.log"
                    if (Test-Path $source) { Copy-Item -LiteralPath $source -Destination (Join-Path $logs "$($fixture.ToLowerInvariant())-$shot-attempt-$attempt$suffix.log") }
                }
            }
        }
        $first = $false
    }
}
$descriptions = @{}
Get-ChildItem -LiteralPath $destination -Filter index.tsv -Recurse | ForEach-Object {
    $folder = $_.DirectoryName
    Import-Csv -LiteralPath $_.FullName -Delimiter "`t" | ForEach-Object {
        $descriptions[(Join-Path $folder $_.File)] = $_.Description
    }
}
$lines = @('# Final review', '', 'Room-area review: programme on the left, area on the right. Cards use the same data as the editable Grasshopper definitions.', '',
    'Generated by tools/examples/Review-Examples.ps1. Each viewport uses a separate RhinoCore process. Safe-mode previews mirror the real Custom Preview inputs; the saved definitions retain native Custom Preview wiring.', '',
    'Selection is transient. Paper selected uses R05 + R09; group uses Bedroom; partial removes R01 from Bedroom. Both plans share the same room keys. Canvas cards use Paper for deterministic review.', '',
    'Showcase has one viewport programme legend (Colour Categories). The Colour Palette + Key Legend demonstration is captioned as a canvas reference in group 4 only. Hello computes Total area and Rooms below 15 m² from the editable area list using native Grasshopper components.', '')
Get-ChildItem -LiteralPath $destination -Filter *.png -Recurse | Sort-Object FullName | ForEach-Object {
    $relative = [IO.Path]::GetRelativePath($destination, $_.FullName).Replace('\', '/')
    $description = $descriptions[$_.FullName]
    if (-not $description) {
        $description = if ($_.BaseName -like 'viewport-*') { "$($_.Directory.Name) viewport, $($_.BaseName.Substring(9)) state; linked room-area review." } else { 'Review image.' }
    }
    $lines += "- [$relative]($relative) — $description"
}
$lines | Set-Content -LiteralPath (Join-Path $destination 'index.md') -Encoding utf8
Write-Output "Review index: $(Join-Path $destination 'index.md')"
